-- =====================================================================
--  Esquema de la base de datos - Nexus Gaming (PostgreSQL / Amazon RDS)
--  usuarios: alineada con UsuarioModel (perfil sincronizado desde Azure AD;
--            sin contraseña, el login lo gestiona Azure).
--  categorias y productos: alineadas con CategoriaModel y ProductoModel.
--  ordenes y detalle_ordenes: usadas por POST /api/ordenes (Productos).
-- =====================================================================

CREATE TYPE "ordenes_estado" AS ENUM (
  'PENDIENTE',
  'PAGADO',
  'ENVIADO',
  'CANCELADO'
);

CREATE TABLE "usuarios" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "azure_oid" varchar(64) UNIQUE NOT NULL,
  "nombre" varchar(100) NOT NULL,
  "email" varchar(150),
  "rol" varchar(100) NOT NULL
);

CREATE TABLE "categorias" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(100) UNIQUE NOT NULL,
  "descripcion" varchar(255)
);

CREATE TABLE "productos" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(150) NOT NULL,
  "descripcion" text,
  "precio" decimal(10,2) NOT NULL,
  "stock" int NOT NULL DEFAULT 0,
  "imagen_url" varchar(500),
  "categoria_id" int NOT NULL
);

CREATE TABLE "ordenes" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" int NOT NULL,
  "fecha" timestamp NOT NULL DEFAULT (now()),
  "total" decimal(10,2) NOT NULL,
  "estado" ordenes_estado NOT NULL DEFAULT 'PENDIENTE'
);

CREATE TABLE "detalle_ordenes" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "orden_id" int NOT NULL,
  "producto_id" int NOT NULL,
  "cantidad" int NOT NULL,
  "precio_unitario" decimal(10,2) NOT NULL
);

COMMENT ON TABLE "usuarios" IS 'Perfil de los usuarios autenticados con Azure AD (clientes y administradores)';

COMMENT ON COLUMN "usuarios"."azure_oid" IS 'Object ID del usuario en Azure AD (claim oid)';

COMMENT ON COLUMN "usuarios"."rol" IS 'Rol vigente según el último token (Admin, Cliente o Sin rol)';

COMMENT ON TABLE "categorias" IS 'Categorías de productos gamer: Teclados, GPUs, Monitores, etc.';

COMMENT ON TABLE "productos" IS 'Catálogo de productos: componentes, periféricos, consolas, sillas gamer, etc.';

COMMENT ON TABLE "ordenes" IS 'Órdenes de compra generadas por los usuarios';

COMMENT ON TABLE "detalle_ordenes" IS 'Detalle de productos incluidos en cada orden (línea de pedido)';

ALTER TABLE "productos" ADD FOREIGN KEY ("categoria_id") REFERENCES "categorias" ("id") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "ordenes" ADD FOREIGN KEY ("usuario_id") REFERENCES "usuarios" ("id") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "detalle_ordenes" ADD FOREIGN KEY ("orden_id") REFERENCES "ordenes" ("id") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "detalle_ordenes" ADD FOREIGN KEY ("producto_id") REFERENCES "productos" ("id") DEFERRABLE INITIALLY IMMEDIATE;
